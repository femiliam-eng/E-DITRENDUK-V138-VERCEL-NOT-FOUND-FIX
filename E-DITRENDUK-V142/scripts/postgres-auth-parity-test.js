'use strict';
const assert=require('node:assert/strict');
const {parity,canonicalPermissions}=require('./postgres-auth-parity');
const account={id:'a1',username:'alfina',email:'a@example.org',name:'Alfina',role:'Pegawai',status:'Aktif',unit:'DITRENDUK',permissions:'["agenda","task-deadline"]',password_hash:'secret-hash',must_change_password:0};
const reset={id:'r1',account_id:'a1',status:'Menunggu'};
const local={accounts:[account],resets:[reset]};
const remote={accounts:[{...account,permissions:['task-deadline','agenda'],must_change_password:false}],resets:[reset]};
assert.equal(parity(local,remote).ok,true);
assert.equal(canonicalPermissions('["agenda","agenda"]'),'["agenda"]');
const missing=parity(local,{accounts:[],resets:[]});
assert(missing.differences.some(x=>x.type==='account_missing'));
assert(missing.differences.some(x=>x.type==='reset_missing'));
const bad=parity(local,{accounts:[{...account,password_hash:'different',role:'Superadmin',permissions:[]}],resets:[{...reset,status:'Selesai'}]});
assert(bad.differences.some(x=>x.type==='password_hash_mismatch'));
assert(bad.differences.some(x=>x.type==='permissions_mismatch'));
assert(bad.differences.some(x=>x.type==='reset_mismatch'));
assert(!JSON.stringify(bad).includes('secret-hash'));
assert(!JSON.stringify(bad).includes('a@example.org'));
console.log('PASS PostgreSQL account, permissions and reset parity tests (no secrets)');
